  function fillProductDetails(main, details) {
    main.querySelector('.breadcrumb [aria-current]').textContent = details.brand + ' ' + details.model;
    main.querySelector('.oct-gildan-brand').textContent = details.brand;
    main.querySelector('#gildan-title').textContent = details.title;
    main.querySelector('.oct-gildan-meta strong').textContent = details.sizes[0] + '–' + details.sizes.at(-1);

    const description = main.querySelector('#gildan-description');
    const identifiers = document.createElement('p');
    const style = document.createElement('strong');
    style.textContent = details.brand + ' style ' + details.style;
    identifiers.append(style, ' · S&S item ' + details.item);
    const summary = document.createElement('p');
    summary.textContent = details.summary;
    const features = document.createElement('ul');
    for (const feature of details.features) {
      const item = document.createElement('li');
      item.textContent = feature;
      features.append(item);
    }
    description.replaceChildren(identifiers, summary, features);

    const table = main.querySelector('#gildan-specs table');
    const header = table.tHead.rows[0];
    header.replaceChildren();
    for (const label of ['Measurement', ...details.sizes]) {
      const cell = document.createElement('th');
      cell.scope = 'col';
      cell.textContent = label;
      header.append(cell);
    }

    const body = table.tBodies[0];
    body.replaceChildren();
    for (const [label, values] of Object.entries(details.rows)) {
      const row = body.insertRow();
      const heading = document.createElement('th');
      heading.scope = 'row';
      heading.textContent = label;
      row.append(heading);
      for (const value of values) row.insertCell().textContent = value;
    }
  }

